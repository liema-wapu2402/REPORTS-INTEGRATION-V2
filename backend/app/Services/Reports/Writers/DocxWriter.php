<?php

namespace App\Services\Reports\Writers;

use PhpOffice\PhpWord\PhpWord;
use PhpOffice\PhpWord\SimpleType\Jc;

class DocxWriter
{
    /**
     * @param  array{
     *   title:string, subtitle?:string, meta?:array<string,string>,
     *   paragraphs?:array<int,string>,
     *   table?:array{headings:array,rows:array},
     *   signatory?:array{name:string,role:string}
     * }  $spec
     */
    public function write(array $spec, string $filename): string
    {
        $word = new PhpWord();
        $word->setDefaultFontName('Calibri');
        $word->setDefaultFontSize(11);
        $word->addTitleStyle(1, ['size' => 22, 'bold' => true, 'color' => '0F172A'], ['spaceAfter' => 80]);

        $section = $word->addSection(['marginLeft' => 1100, 'marginRight' => 1100, 'marginTop' => 1000, 'marginBottom' => 1000]);

        $section->addTitle($spec['title'], 1);
        if (! empty($spec['subtitle'])) {
            $section->addText($spec['subtitle'], ['color' => '0891B2', 'size' => 12, 'bold' => true]);
        }
        $section->addLine(['weight' => 1.5, 'width' => 450, 'height' => 0, 'color' => '0891B2']);
        $section->addTextBreak(1);

        foreach ($spec['meta'] ?? [] as $label => $value) {
            $run = $section->addTextRun(['spaceAfter' => 40]);
            $run->addText(str_pad($label . ':', 12), ['bold' => true, 'color' => '475569']);
            $run->addText(' ' . $value);
        }
        if (! empty($spec['meta'])) {
            $section->addTextBreak(1);
        }

        foreach ($spec['paragraphs'] ?? [] as $p) {
            $section->addText($p, [], ['spaceAfter' => 160, 'alignment' => Jc::BOTH]);
        }

        if (! empty($spec['table']['rows'])) {
            $headings = $spec['table']['headings'];
            $table = $section->addTable([
                'borderSize' => 4, 'borderColor' => 'CBD5E1', 'cellMargin' => 70, 'width' => 5000, 'unit' => 'pct',
            ]);
            $table->addRow(420);
            foreach ($headings as $h) {
                $table->addCell(null, ['bgColor' => '0F172A'])->addText(
                    ucwords(str_replace('_', ' ', (string) $h)),
                    ['bold' => true, 'color' => 'FFFFFF', 'size' => 10]
                );
            }
            foreach ($spec['table']['rows'] as $i => $row) {
                $table->addRow();
                foreach (array_values((array) $row) as $value) {
                    $numeric = is_numeric($value);
                    $table->addCell(null, ['bgColor' => $i % 2 ? 'F1F5F9' : 'FFFFFF'])->addText(
                        $numeric ? number_format((float) $value, 2) : (string) $value,
                        ['size' => 10],
                        ['alignment' => $numeric ? Jc::END : Jc::START]
                    );
                }
            }
            $section->addTextBreak(1);
        }

        if (! empty($spec['signatory'])) {
            $section->addTextBreak(2);
            $section->addText('______________________________');
            $section->addText($spec['signatory']['name'], ['bold' => true]);
            $section->addText($spec['signatory']['role'], ['color' => '64748B']);
        }

        $footer = $section->addFooter();
        $footer->addPreserveText(
            'Generated by Report Integrations  ·  Page {PAGE} of {NUMPAGES}',
            ['size' => 8, 'color' => '94A3B8'],
            ['alignment' => Jc::CENTER]
        );

        $path = ReportPaths::for($filename);
        $word->save($path, 'Word2007');

        return $path;
    }
}
